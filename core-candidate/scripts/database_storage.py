STORAGE_PACKAGE_FILE = "storage_package.json"
STORAGE_PUBLICATION_FILE = "storage_publication.json"
STORAGE_RECEIPT_FILE = "storage_receipt.json"
SOURCE_ARCHIVE_FILE = source_archive_file()
GENERATED_MARKER = "<!-- Generated by GRDR Storage -->"
GENERATED_PY_MARKER = "# Generated by GRDR Storage"
HUMAN_READABLE_MARKER = "<!-- Human-readable sections are maintained in this source repository. -->"
IGNORED_FILESYSTEM_METADATA = {".DS_Store"}
RUNTIME_DESCRIPTOR_FILE = "runtime.json"
RUNTIME_AUDIT_FILE = "runtime_audit.json"


def is_ignored_filesystem_metadata(path: Path) -> bool:
    """Exclude host filesystem sidecars from the logical database snapshot."""
    return any(part in IGNORED_FILESYSTEM_METADATA or part.startswith("._") for part in path.parts)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def file_record(path: Path, relative: str, component: str) -> dict[str, Any]:
    return {
        "path": relative,
        "component": component,
        "sha256": sha256_file(path),
        "size_bytes": path.stat().st_size,
    }


def asset_record(path: Path, component: str, logical_paths: list[str]) -> dict[str, Any]:
    return {
        "name": path.name,
        "component": component,
        "sha256": sha256_file(path),
        "size_bytes": path.stat().st_size,
        "logical_paths": sorted(logical_paths),
    }


def resolve_input(value: str, base: Path) -> Path:
    path = Path(value).expanduser()
    if not path.is_absolute():
        path = base / path
    return path.resolve()


def checked_files(path: Path) -> list[Path]:
    if not path.exists():
        raise ValueError(f"storage input does not exist: {path}")
    if path.is_symlink():
        raise ValueError(f"storage inputs cannot be symbolic links: {path}")
    if path.is_file():
        return [path]
    files = []
    for item in sorted(path.rglob("*")):
        if is_ignored_filesystem_metadata(item.relative_to(path)):
            continue
        if item.is_symlink():
            raise ValueError(f"storage inputs cannot contain symbolic links: {item}")
        if item.is_file():
            files.append(item)
    if not files:
        raise ValueError(f"storage input contains no files: {path}")
    return files


def copy_input(source: Path, destination: Path) -> list[Path]:
    files = checked_files(source)
    for item in files:
        relative = Path(item.name) if source.is_file() else item.relative_to(source)
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(item, target)
    return [destination / (Path(item.name) if source.is_file() else item.relative_to(source)) for item in files]


def copy_project_knowledge(project_dir: Path, destination: Path) -> None:
    excluded = {STORAGE_PACKAGE_FILE, STORAGE_PUBLICATION_FILE, STORAGE_RECEIPT_FILE}
    for source in sorted(project_dir.rglob("*")):
        if is_ignored_filesystem_metadata(source.relative_to(project_dir)):
            continue
        if source.is_symlink():
            raise ValueError(f"deep-map project contains an unsupported symbolic link: {source}")
        if not source.is_file() or source.name in excluded or "__pycache__" in source.parts:
            continue
        relative = source.relative_to(project_dir)
        target = destination / "project" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)


def display_text(record: dict[str, Any]) -> str:
    values = []
    for key in ("name", "label", "title", "description", "definition"):
        value = record.get(key)
        if isinstance(value, str):
            values.append(value)
    aliases = record.get("aliases")
    if isinstance(aliases, list):
        values.extend(str(value) for value in aliases)
    return " | ".join(dict.fromkeys(values))


def build_agent_index(project_dir: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(destination)
    try:
        connection.executescript(
            """
            PRAGMA journal_mode=OFF;
            PRAGMA synchronous=OFF;
            CREATE TABLE metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
            CREATE TABLE records (
              id TEXT PRIMARY KEY,
              entity_type TEXT NOT NULL,
              label TEXT NOT NULL,
              search_text TEXT NOT NULL,
              payload_json TEXT NOT NULL
            );
            CREATE INDEX records_entity_type ON records(entity_type);
            CREATE INDEX records_label ON records(label);
            CREATE TABLE relationships (
              id TEXT PRIMARY KEY,
              subject_id TEXT,
              predicate TEXT,
              object_id TEXT,
              payload_json TEXT NOT NULL
            );
            CREATE INDEX relationships_subject ON relationships(subject_id);
            CREATE INDEX relationships_object ON relationships(object_id);
            """
        )
        project = read_json(project_dir / PROJECT_FILE)
        connection.executemany(
            "INSERT INTO metadata(key, value) VALUES (?, ?)",
            [("project_id", project["id"]), ("source_id", project["source_id"]), ("built_at", now())],
        )
        staging = project_dir / STAGING_DIR
        for path in sorted(staging.glob("*.jsonl")):
            if is_ignored_filesystem_metadata(path.relative_to(staging)):
                continue
            entity_type = path.stem
            for record in read_jsonl(path):
                payload = json.dumps(record, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
                if entity_type == "relationships":
                    connection.execute(
                        "INSERT INTO relationships VALUES (?, ?, ?, ?, ?)",
                        (record["id"], record.get("subject_id"), record.get("predicate"), record.get("object_id"), payload),
                    )
                else:
                    label = str(record.get("label") or record.get("name") or record.get("title") or record["id"])
                    connection.execute(
                        "INSERT INTO records VALUES (?, ?, ?, ?, ?)",
                        (record["id"], entity_type, label, display_text(record), payload),
                    )
        try:
            connection.execute("CREATE VIRTUAL TABLE record_search USING fts5(id UNINDEXED, label, search_text)")
            connection.execute("INSERT INTO record_search SELECT id, label, search_text FROM records")
        except sqlite3.OperationalError:
            connection.execute("CREATE INDEX records_search_text ON records(search_text)")
        connection.commit()
        connection.execute("VACUUM")
    finally:
        connection.close()


def stage_source_runtime(spec: dict[str, Any], project: dict[str, Any], agent_dir: Path) -> dict[str, Any]:
    descriptor_path = resolve_input(spec["runtime"]["descriptor"], ROOT)
    descriptor = read_json(descriptor_path)
    errors = validate_schema(descriptor, "source_runtime.schema.json", RUNTIME_DESCRIPTOR_FILE)
    if errors:
        raise ValueError("invalid source runtime descriptor: " + "; ".join(errors))
    if descriptor["source_id"] != project["source_id"]:
        raise ValueError("source runtime descriptor source_id does not match the deep-map project")
    inputs = [resolve_input(value, ROOT) for value in spec["runtime"]["files"]]
    names = [path.name for path in inputs]
    if len(names) != len(set(names)):
        raise ValueError("source runtime files must have unique basenames")
    if descriptor["entrypoint"] not in names:
        raise ValueError("source runtime entrypoint is absent from runtime.files")
    agent_dir.mkdir(parents=True, exist_ok=True)
    write_json(agent_dir / RUNTIME_DESCRIPTOR_FILE, descriptor)
    for source in inputs:
        if not source.is_file() or source.is_symlink():
            raise ValueError(f"runtime input must be a regular file: {source}")
        shutil.copy2(source, agent_dir / source.name)
    return descriptor


def run_source_runtime_self_test(agent_dir: Path, descriptor: dict[str, Any]) -> dict[str, Any]:
    entrypoint = agent_dir / descriptor["entrypoint"]
    index = agent_dir / descriptor["agent_index"]
    try:
        completed = subprocess.run(
            [sys.executable, str(entrypoint), "self-test", "--index", str(index)],
            cwd=agent_dir,
            capture_output=True,
            text=True,
            timeout=120,
        )
    except subprocess.TimeoutExpired as exc:
        raise ValueError("source runtime self-test exceeded 120 seconds") from exc
    if completed.returncode:
        detail = (completed.stderr or completed.stdout).strip()
        raise ValueError(f"source runtime self-test failed: {detail}")
    try:
        report = json.loads(completed.stdout)
    except json.JSONDecodeError as exc:
        raise ValueError("source runtime self-test did not emit one JSON object") from exc
    if not isinstance(report, dict):
        raise ValueError("source runtime self-test result must be a JSON object")
    required = {
        "source_id": descriptor["source_id"],
        "status": "ready",
        "unresolved_variable_count": 0,
    }
    for key, expected in required.items():
        if report.get(key) != expected:
            raise ValueError(f"source runtime self-test {key} must equal {expected!r}")
    connection = sqlite3.connect(index)
    try:
        indexed_variable_count = connection.execute(
            "SELECT COUNT(*) FROM records WHERE entity_type = 'variables'"
        ).fetchone()[0]
    finally:
        connection.close()
    variable_count = report.get("variable_count")
    resolvable_count = report.get("resolvable_variable_count")
    if variable_count != indexed_variable_count:
        raise ValueError("source runtime self-test variable count differs from the Agent index")
    if resolvable_count != variable_count:
        raise ValueError("source runtime self-test did not resolve every registered variable")
    return report


def create_deterministic_tar_gz(source: Path, output: Path, archive_root: str) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as compressed:
            with tarfile.open(fileobj=compressed, mode="w", format=tarfile.PAX_FORMAT) as archive:
                for path in sorted(source.rglob("*")):
                    if is_ignored_filesystem_metadata(path.relative_to(source)):
                        continue
                    if not path.is_file():
                        continue
                    relative = path.relative_to(source)
                    info = archive.gettarinfo(str(path), arcname=str(Path(archive_root) / relative))
                    info.uid = info.gid = 0
                    info.uname = info.gname = ""
                    info.mtime = 0
                    info.mode = 0o644
                    with path.open("rb") as handle:
                        archive.addfile(info, handle)


def inventory(logical_root: Path) -> list[dict[str, Any]]:
    records = []
    for path in sorted(logical_root.rglob("*")):
        if is_ignored_filesystem_metadata(path.relative_to(logical_root)):
            continue
        if not path.is_file():
            continue
        relative = path.relative_to(logical_root).as_posix()
        if relative.startswith("receipts/"):
            continue
        component = relative.split("/", 1)[0]
        records.append(file_record(path, relative, component))
    return records


def package_payload(
    project: dict[str, Any],
    spec: dict[str, Any],
    archive_receipt: dict[str, Any],
    elements_path: Path,
    release_assets_path: Path,
    logical_files: list[dict[str, Any]],
    release_assets: list[dict[str, Any]],
    runtime: dict[str, Any],
    runtime_audit: dict[str, Any],
    prepared_at: str,
) -> dict[str, Any]:
    payload = {
        "schema_version": "2.0.0",
        "project_id": project["id"],
        "source_id": project["source_id"],
        "source_slug": spec["source_slug"],
        "snapshot_id": spec["snapshot_id"],
        "core_version": spec["core"]["version"],
        "core_repository": spec["core"]["repository"],
        "source_repository": spec["source_repository"]["github"],
        "source_repository_path": str(resolve_input(spec["source_repository"]["local_path"], ROOT)),
        "release_tag": spec["release"]["tag"],
        "release_title": spec["release"]["title"],
        "release_assets_path": str(release_assets_path),
        "elements_snapshot_path": str(elements_path),
        "canonical_archive_fingerprint": archive_receipt["receipt_fingerprint"],
        "knowledge_file_count": sum(item["component"] == "knowledge" for item in logical_files),
        "observation_file_count": sum(item["component"] == "observations" for item in logical_files),
        "logical_file_count": len(logical_files),
        "logical_size_bytes": sum(item["size_bytes"] for item in logical_files),
        "logical_files": logical_files,
        "release_assets": release_assets,
        "runtime": runtime,
        "runtime_audit": runtime_audit,
        "logical_content_fingerprint": fingerprint(logical_files),
        "prepared_at": prepared_at,
    }
    payload["package_fingerprint"] = fingerprint(payload)
    return payload


def generated_readme(project: dict[str, Any], package: dict[str, Any]) -> str:
    return f"""{GENERATED_MARKER}
# {project['title']} — GRDR source repository

This private repository stores the reviewable GRDR configuration for `{project['source_id']}`.
It references GRDR Core `{package['core_version']}` and does not copy the Core Skills.

## Latest snapshot

- Snapshot: `{package['snapshot_id']}`
- Release: `{package['release_tag']}`
- Complete knowledge files: {package['knowledge_file_count']}
- Complete observation files: {package['observation_file_count']}
- Agent runtime: `{package['runtime']['protocol_version']}` via `agent/{package['runtime']['entrypoint']}`
- Runtime variable coverage: {package['runtime_audit']['resolvable_variable_count']}/{package['runtime_audit']['variable_count']}
- Logical content fingerprint: `{package['logical_content_fingerprint']}`

The GitHub Release is the compressed distribution copy. The Elements directory is the expanded
working copy. `snapshots/{package['snapshot_id']}/manifest.json` binds both representations.
"""


def write_generated(path: Path, content: str) -> None:
    if path.exists():
        current = path.read_text(encoding="utf-8")
        if current == content:
            return
        if not current.startswith((GENERATED_MARKER, GENERATED_PY_MARKER)):
            raise ValueError(f"refusing to overwrite a non-GRDR file: {path}")
    atomic_write_text(path, content)


def write_source_readme(path: Path, generated: str) -> None:
    if path.is_file():
        current = path.read_text(encoding="utf-8")
        if HUMAN_READABLE_MARKER in current:
            human = HUMAN_READABLE_MARKER + current.split(HUMAN_READABLE_MARKER, 1)[1]
            generated = generated.rstrip() + "\n\n" + human.lstrip()
    write_generated(path, generated)


def materialize_source_repository(
    project_dir: Path,
    project: dict[str, Any],
    spec: dict[str, Any],
    package: dict[str, Any],
) -> None:
    repository = Path(package["source_repository_path"])
    repository.mkdir(parents=True, exist_ok=True)
    ignore_path = repository / ".gitignore"
    ignore = ignore_path.read_text(encoding="utf-8") if ignore_path.exists() else ""
    line = ".grdr-release-assets/"
    if line not in ignore.splitlines():
        atomic_write_text(ignore_path, (ignore.rstrip() + "\n" + line + "\n").lstrip("\n"))
    write_source_readme(repository / "README.md", generated_readme(project, package))
    source_config = {
        "schema_version": "2.0.0",
        "source_id": project["source_id"],
        "core_repository": package["core_repository"],
        "core_version": package["core_version"],
        "latest_snapshot": package["snapshot_id"],
        "release_tag": package["release_tag"],
        "runtime": package["runtime"],
    }
    write_json(repository / "grdr-source.json", source_config)
    snapshot_dir = repository / "snapshots" / package["snapshot_id"]
    write_json(snapshot_dir / "manifest.json", package)
    shutil.copy2(project_dir / ARCHIVE_RECEIPT_FILE, snapshot_dir / "canonical_archive_receipt.json")
    plan_dir = repository / "plan" / package["snapshot_id"]
    write_json(plan_dir / "diagnostic_plan.json", project["diagnostic_plan"])
    write_json(plan_dir / "scope.json", project["scope"])
    shutil.copy2(project_dir / UNIT_FILE, plan_dir / UNIT_FILE)
    adapter_dir = repository / "adapters"
    for value in spec["adapter_inputs"]:
        source = resolve_input(value, ROOT)
        if not source.is_file() or source.is_symlink():
            raise ValueError(f"adapter input must be a regular file: {source}")
        target = adapter_dir / source.name
        if source.resolve() == target.resolve():
            continue
        if target.exists() and sha256_file(target) != sha256_file(source):
            raise ValueError(f"refusing to overwrite a different adapter: {target}")
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
    runtime_dir = repository / "runtime"
    runtime_dir.mkdir(parents=True, exist_ok=True)
    write_json(runtime_dir / RUNTIME_DESCRIPTOR_FILE, package["runtime"])
    for value in spec["runtime"]["files"]:
        source = resolve_input(value, ROOT)
        target = runtime_dir / source.name
        if source.resolve() == target.resolve():
            continue
        if target.exists() and sha256_file(target) != sha256_file(source):
            raise ValueError(f"refusing to overwrite a different runtime file: {target}")
        shutil.copy2(source, target)
    write_json(runtime_dir / RUNTIME_AUDIT_FILE, package["runtime_audit"])
    test_content = f'''{GENERATED_PY_MARKER}
import hashlib
import json
from pathlib import Path


def test_snapshot_manifest_is_self_consistent():
    root = Path(__file__).resolve().parents[1]
    manifest = json.loads((root / "snapshots" / "{package['snapshot_id']}" / "manifest.json").read_text())
    payload = dict(manifest)
    recorded = payload.pop("package_fingerprint")
    encoded = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()
    assert hashlib.sha256(encoded).hexdigest() == recorded
    assert manifest["source_id"] == "{project['source_id']}"
    assert manifest["runtime_audit"]["unresolved_variable_count"] == 0
    assert manifest["runtime_audit"]["variable_count"] == manifest["runtime_audit"]["resolvable_variable_count"]
'''
    write_generated(repository / "tests" / "test_snapshot_manifest.py", test_content)


def prepare_database_storage(project_dir: str | Path, spec_file: str | Path) -> dict[str, Any]:
    target = resolve_project_dir(project_dir)
    require_project(target)
    project = read_json(target / PROJECT_FILE)
    spec_path = Path(spec_file).expanduser().resolve()
    spec = read_json(spec_path)
    errors = validate_schema(spec, "database_storage_spec.schema.json", "storage_spec")
    if errors:
        raise ValueError("invalid database storage specification: " + "; ".join(errors))
    if spec["source_id"] != project["source_id"]:
        raise ValueError("storage specification source_id does not match the deep-map project")
    core_version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    if spec["core"]["version"] != core_version:
        raise ValueError(f"storage specification requires GRDR Core {spec['core']['version']}, current is {core_version}")
    if not archive_receipt_is_valid(target, project):
        if not (target / "archive_package.json").is_file():
            prepare_database_deep_map_archive(target)
        archive_database_deep_map(target)
        project = read_json(target / PROJECT_FILE)
    if not archive_receipt_is_valid(target, project):
        raise ValueError("canonical archive transaction is incomplete; Storage cannot package unpromoted records")
    archive_receipt = read_json(target / ARCHIVE_RECEIPT_FILE)
    source_repository = resolve_input(spec["source_repository"]["local_path"], ROOT)
    elements_root = resolve_input(spec["elements_root"], ROOT)
    elements_root.mkdir(parents=True, exist_ok=True)
    elements_path = elements_root / "sources" / spec["source_slug"] / "snapshots" / spec["snapshot_id"]
    release_assets_path = source_repository / ".grdr-release-assets" / spec["snapshot_id"]
    if (target / STORAGE_PACKAGE_FILE).is_file():
        existing = read_json(target / STORAGE_PACKAGE_FILE)
        if existing.get("snapshot_id") == spec["snapshot_id"]:
            materialize_source_repository(target, project, spec, existing)
            audit = audit_database_storage(target)
            if not audit["errors"]:
                return {"operation": "prepare_database_storage", "status": "already_prepared", "package": existing, "audit": audit}
        raise ValueError("a different or invalid storage package already exists; use a new snapshot_id")
    if elements_path.exists():
        raise ValueError(f"Elements snapshot path already exists: {elements_path}")
    if release_assets_path.exists():
        raise ValueError(f"release asset path already exists: {release_assets_path}")

    temporary_parent = elements_path.parent
    temporary_parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=f".{spec['snapshot_id']}.", dir=temporary_parent) as temporary:
        workspace = Path(temporary)
        logical_root = workspace / "logical"
        knowledge = logical_root / "knowledge"
        copy_project_knowledge(target, knowledge)
        for value in spec["adapter_inputs"]:
            source = resolve_input(value, ROOT)
            if not source.is_file() or source.is_symlink():
                raise ValueError(f"adapter input must be a regular file: {source}")
            (knowledge / "adapters").mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, knowledge / "adapters" / source.name)
        agent_dir = logical_root / "agent"
        build_agent_index(target, agent_dir / "grdr-agent-index.sqlite")
        runtime = stage_source_runtime(spec, project, agent_dir)
        runtime_audit = run_source_runtime_self_test(agent_dir, runtime)
        write_json(agent_dir / RUNTIME_AUDIT_FILE, runtime_audit)
        observation_names = set()
        for item in spec["observation_inputs"]:
            if item["name"] in observation_names:
                raise ValueError(f"duplicate observation input name: {item['name']}")
            observation_names.add(item["name"])
            copy_input(resolve_input(item["path"], spec_path.parent), logical_root / "observations" / item["name"])
        logical_files = inventory(logical_root)
        if not any(item["component"] == "observations" for item in logical_files):
            raise ValueError("Storage requires at least one actual observation-data file")
        if sum(item["size_bytes"] for item in logical_files if item["component"] == "observations") == 0:
            raise ValueError("observation-data inputs contain zero total bytes")

        assets = workspace / "assets"
        knowledge_asset = assets / f"{spec['source_slug']}-{spec['snapshot_id']}-knowledge.tar.gz"
        create_deterministic_tar_gz(logical_root / "knowledge", knowledge_asset, "knowledge")
        agent_asset = assets / f"{spec['source_slug']}-{spec['snapshot_id']}-agent-runtime.tar.gz"
        create_deterministic_tar_gz(logical_root / "agent", agent_asset, "agent")
        release_assets = [
            asset_record(knowledge_asset, "knowledge", [item["path"] for item in logical_files if item["component"] == "knowledge"]),
            asset_record(agent_asset, "agent", [item["path"] for item in logical_files if item["component"] == "agent"]),
        ]
        for name in sorted(observation_names):
            source = logical_root / "observations" / name
            output = assets / f"{spec['source_slug']}-{spec['snapshot_id']}-observations-{name}.tar.gz"
            create_deterministic_tar_gz(source, output, f"observations/{name}")
            prefix = f"observations/{name}/"
            release_assets.append(asset_record(output, "observations", [item["path"] for item in logical_files if item["path"].startswith(prefix)]))
        prepared_at = now()
        package = package_payload(
            project, spec, archive_receipt, elements_path, release_assets_path,
            logical_files, release_assets, runtime, runtime_audit, prepared_at,
        )
        validation_errors = validate_schema(package, "database_storage_package.schema.json", STORAGE_PACKAGE_FILE)
        if validation_errors:
            raise ValueError("generated storage package failed Schema validation: " + "; ".join(validation_errors))
        write_json(assets / "manifest.json", package)
        shutil.move(str(logical_root), str(elements_path))
        release_assets_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(assets), str(release_assets_path))

    write_json(target / STORAGE_PACKAGE_FILE, package)
    materialize_source_repository(target, project, spec, package)
    audit = audit_database_storage(target)
    if audit["errors"]:
        raise ValueError("prepared database storage failed audit: " + "; ".join(audit["errors"]))
    project = read_json(target / PROJECT_FILE)
    project["workflow_status"] = "ready_for_storage"
    project["current_phase"] = "storage"
    project["next_actions"] = ["publish-database-storage", "database-storage-status"]
    append_history(project, "prepare-database-storage", "Materialized the source repository, complete knowledge artifact, executable Agent runtime and index, observation artifacts, and matching Elements snapshot.")
    write_json(target / PROJECT_FILE, project)
    return {"operation": "prepare_database_storage", "status": "ready_for_publish", "package": package, "audit": audit_database_storage(target)}


def archive_members(path: Path) -> dict[str, dict[str, Any]]:
    result = {}
    with tarfile.open(path, mode="r:gz") as archive:
        for member in archive.getmembers():
            if not member.isfile():
                continue
            handle = archive.extractfile(member)
            if handle is None:
                continue
            digest = hashlib.sha256()
            size = 0
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
                size += len(chunk)
            result[member.name] = {"sha256": digest.hexdigest(), "size_bytes": size}
    return result


def publication_asset_records(package: dict[str, Any]) -> list[dict[str, Any]]:
    assets = list(package["release_assets"])
    manifest = Path(package["release_assets_path"]) / "manifest.json"
    assets.append(asset_record(manifest, "manifest", []))
    return sorted(assets, key=lambda item: item["name"])


def storage_receipt_is_valid(project_dir: str | Path, project: dict[str, Any] | None = None) -> bool:
    target = resolve_project_dir(project_dir)
    package_path = target / STORAGE_PACKAGE_FILE
    publication_path = target / STORAGE_PUBLICATION_FILE
    receipt_path = target / STORAGE_RECEIPT_FILE
    if not all(path.is_file() for path in (package_path, publication_path, receipt_path)):
        return False
    package = read_json(package_path)
    publication = read_json(publication_path)
    receipt = read_json(receipt_path)
    if validate_schema(package, "database_storage_package.schema.json", STORAGE_PACKAGE_FILE):
        return False
    if validate_schema(publication, "database_storage_publication.schema.json", STORAGE_PUBLICATION_FILE):
        return False
    if validate_schema(receipt, "database_storage_receipt.schema.json", STORAGE_RECEIPT_FILE):
        return False
    receipt_payload = {key: value for key, value in receipt.items() if key != "receipt_fingerprint"}
    return (
        fingerprint({key: value for key, value in package.items() if key != "package_fingerprint"}) == package["package_fingerprint"]
        and fingerprint({key: value for key, value in publication.items() if key != "publication_fingerprint"}) == publication["publication_fingerprint"]
        and fingerprint(receipt_payload) == receipt["receipt_fingerprint"]
        and receipt["package_fingerprint"] == package["package_fingerprint"]
        and receipt["publication_fingerprint"] == publication["publication_fingerprint"]
        and receipt["source_id"] == package["source_id"]
        and (project is None or receipt["project_id"] == project["id"])
    )


def audit_database_storage(project_dir: str | Path) -> dict[str, Any]:
    target = resolve_project_dir(project_dir)
    require_project(target)
    project = read_json(target / PROJECT_FILE)
    errors: list[str] = []
    warnings: list[str] = []
    package_path = target / STORAGE_PACKAGE_FILE
    if not package_path.is_file():
        return {
            "operation": "audit_database_storage", "project_id": project["id"], "project_dir": str(target),
            "prepared": False, "ready_for_publish": False, "storage_complete": False,
            "errors": [f"missing {STORAGE_PACKAGE_FILE}"], "warnings": [],
        }
    package = read_json(package_path)
    errors.extend(validate_schema(package, "database_storage_package.schema.json", STORAGE_PACKAGE_FILE))
    expected_package_fingerprint = fingerprint({key: value for key, value in package.items() if key != "package_fingerprint"})
    if package.get("package_fingerprint") != expected_package_fingerprint:
        errors.append("storage package fingerprint is stale")
    if package.get("project_id") != project["id"] or package.get("source_id") != project["source_id"]:
        errors.append("storage package identity does not match the deep-map project")
    elements = Path(package["elements_snapshot_path"])
    if not elements.is_dir():
        errors.append(f"Elements snapshot is missing: {elements}")
        actual_files = []
    else:
        actual_files = inventory(elements)
        if actual_files != package["logical_files"]:
            errors.append("Elements logical file inventory or SHA-256 values differ from the storage package")
    assets_path = Path(package["release_assets_path"])
    expected_logical = {item["path"]: {"sha256": item["sha256"], "size_bytes": item["size_bytes"]} for item in package["logical_files"]}
    covered: dict[str, dict[str, Any]] = {}
    for asset in package["release_assets"]:
        path = assets_path / asset["name"]
        if not path.is_file():
            errors.append(f"release asset is missing: {path}")
            continue
        if sha256_file(path) != asset["sha256"] or path.stat().st_size != asset["size_bytes"]:
            errors.append(f"release asset checksum or size mismatch: {asset['name']}")
            continue
        if asset["component"] in {"knowledge", "agent", "observations"}:
            members = archive_members(path)
            if sorted(members) != sorted(asset["logical_paths"]):
                errors.append(f"release asset logical members differ from manifest: {asset['name']}")
            covered.update(members)
    if covered != expected_logical:
        errors.append("GitHub Release assets and Elements do not represent the same logical snapshot")
    manifest_path = assets_path / "manifest.json"
    if not manifest_path.is_file() or read_json(manifest_path) != package:
        errors.append("release manifest is missing or differs from storage_package.json")
    if elements.is_dir():
        agent_dir = elements / "agent"
        descriptor_path = agent_dir / RUNTIME_DESCRIPTOR_FILE
        if not descriptor_path.is_file() or read_json(descriptor_path) != package.get("runtime"):
            errors.append("Elements source runtime descriptor is missing or differs from the storage package")
        else:
            try:
                runtime_audit = run_source_runtime_self_test(agent_dir, package["runtime"])
                if runtime_audit != package.get("runtime_audit"):
                    errors.append("Elements source runtime audit differs from the sealed runtime audit")
            except ValueError as exc:
                errors.append(str(exc))
    repository = Path(package["source_repository_path"])
    required_repo_files = [
        repository / "README.md", repository / "grdr-source.json",
        repository / "snapshots" / package["snapshot_id"] / "manifest.json",
        repository / "snapshots" / package["snapshot_id"] / "canonical_archive_receipt.json",
        repository / "plan" / package["snapshot_id"] / "diagnostic_plan.json",
        repository / "plan" / package["snapshot_id"] / UNIT_FILE,
        repository / "tests" / "test_snapshot_manifest.py",
        repository / "runtime" / RUNTIME_DESCRIPTOR_FILE,
        repository / "runtime" / package["runtime"]["entrypoint"],
        repository / "runtime" / RUNTIME_AUDIT_FILE,
    ]
    for path in required_repo_files:
        if not path.is_file():
            errors.append(f"source repository file is missing: {path}")
    publication_present = (target / STORAGE_PUBLICATION_FILE).is_file()
    if publication_present:
        publication = read_json(target / STORAGE_PUBLICATION_FILE)
        errors.extend(validate_schema(publication, "database_storage_publication.schema.json", STORAGE_PUBLICATION_FILE))
        if fingerprint({key: value for key, value in publication.items() if key != "publication_fingerprint"}) != publication.get("publication_fingerprint"):
            errors.append("storage publication fingerprint is stale")
        if publication.get("assets") != publication_asset_records(package):
            errors.append("published GitHub asset inventory differs from the prepared Release assets")
        if publication.get("release_tag") != package["release_tag"]:
            errors.append("published release tag differs from the storage package")
    else:
        warnings.append("The complete local snapshot is prepared but has not yet been verified as a GitHub Release.")
    receipt_valid = storage_receipt_is_valid(target, project) if publication_present else False
    central_card_valid = False
    if receipt_valid:
        publication = read_json(target / STORAGE_PUBLICATION_FILE)
        receipt = read_json(target / STORAGE_RECEIPT_FILE)
        cards = read_jsonl(SOURCE_ARCHIVE_FILE) if SOURCE_ARCHIVE_FILE.exists() else []
        card = next((item for item in cards if item.get("id") == f"grdr:source-archive:{package['source_slug']}"), None)
        expected_card = {
            "schema_version": "2.0.0",
            "id": f"grdr:source-archive:{package['source_slug']}",
            "source_id": project["source_id"],
            "repository": publication["repository_url"],
            "latest_snapshot": package["snapshot_id"],
            "release": publication["release_url"],
            "manifest": f"{publication['repository_url']}/releases/download/{package['release_tag']}/manifest.json",
            "archive_fingerprint": package["logical_content_fingerprint"],
            "core_version": package["core_version"],
            "status": "complete",
            "updated_at": receipt["stored_at"],
            "runtime": {
                "protocol_version": package["runtime"]["protocol_version"],
                "asset": next(item["name"] for item in package["release_assets"] if item["component"] == "agent"),
                "entrypoint": f"agent/{package['runtime']['entrypoint']}",
                "agent_index": f"agent/{package['runtime']['agent_index']}",
                "operations": package["runtime"]["operations"],
            },
        }
        central_card_valid = card == expected_card
        if not central_card_valid:
            errors.append("GRDR central source-archive card is missing or differs from the completed snapshot")
    return {
        "operation": "audit_database_storage",
        "project_id": project["id"],
        "project_dir": str(target),
        "snapshot_id": package["snapshot_id"],
        "prepared": not errors or (not publication_present and all("publication" not in item for item in errors)),
        "ready_for_publish": not errors and not publication_present,
        "storage_complete": not errors and receipt_valid and central_card_valid,
        "logical_file_count": package["logical_file_count"],
        "knowledge_file_count": package["knowledge_file_count"],
        "observation_file_count": package["observation_file_count"],
        "logical_size_bytes": package["logical_size_bytes"],
        "logical_content_fingerprint": package["logical_content_fingerprint"],
        "release_asset_count": len(package["release_assets"]) + 1,
        "elements_snapshot_path": package["elements_snapshot_path"],
        "source_repository_path": package["source_repository_path"],
        "publication_present": publication_present,
        "receipt_valid": receipt_valid,
        "central_card_valid": central_card_valid,
        "errors": errors,
        "warnings": warnings,
    }


def record_database_storage_publication(project_dir: str | Path, publication_file: str | Path) -> dict[str, Any]:
    target = resolve_project_dir(project_dir)
    project = read_json(target / PROJECT_FILE)
    package = read_json(target / STORAGE_PACKAGE_FILE)
    publication = read_json(Path(publication_file).expanduser().resolve())
    if storage_receipt_is_valid(target, project) and (target / STORAGE_PUBLICATION_FILE).is_file():
        existing = read_json(target / STORAGE_PUBLICATION_FILE)
        if existing == publication:
            return {
                "operation": "record_database_storage_publication",
                "status": "already_recorded",
                "receipt": read_json(target / STORAGE_RECEIPT_FILE),
                "audit": audit_database_storage(target),
            }
        raise ValueError("a different verified publication is already sealed for this snapshot")
    local_audit = audit_database_storage(target)
    if local_audit["errors"] or not local_audit["ready_for_publish"]:
        raise ValueError("local Storage package is not ready for publication recording: " + "; ".join(local_audit["errors"] or local_audit["warnings"]))
    errors = validate_schema(publication, "database_storage_publication.schema.json", "publication")
    if errors:
        raise ValueError("invalid storage publication: " + "; ".join(errors))
    if fingerprint({key: value for key, value in publication.items() if key != "publication_fingerprint"}) != publication["publication_fingerprint"]:
        raise ValueError("storage publication fingerprint is invalid")
    for key in ("project_id", "source_id", "snapshot_id", "release_tag"):
        expected_key = "release_tag" if key == "release_tag" else key
        if publication[key] != package[expected_key]:
            raise ValueError(f"storage publication {key} does not match the package")
    expected_repository_url = f"https://github.com/{package['source_repository']}"
    if publication["repository_url"].rstrip("/") != expected_repository_url:
        raise ValueError("storage publication repository_url does not match the configured private source repository")
    if not publication["release_url"].startswith(expected_repository_url + "/releases/"):
        raise ValueError("storage publication release_url is outside the configured source repository")
    if publication["assets"] != publication_asset_records(package):
        raise ValueError("storage publication asset inventory does not match the prepared files")
    timestamp = now()
    receipt = {
        "schema_version": "2.0.0",
        "project_id": project["id"],
        "source_id": project["source_id"],
        "snapshot_id": package["snapshot_id"],
        "package_fingerprint": package["package_fingerprint"],
        "publication_fingerprint": publication["publication_fingerprint"],
        "repository_url": publication["repository_url"],
        "release_url": publication["release_url"],
        "elements_snapshot_path": package["elements_snapshot_path"],
        "logical_content_fingerprint": package["logical_content_fingerprint"],
        "canonical_archive_fingerprint": package["canonical_archive_fingerprint"],
        "runtime_protocol_version": package["runtime"]["protocol_version"],
        "runtime_asset": next(item["name"] for item in package["release_assets"] if item["component"] == "agent"),
        "status": "complete",
        "stored_at": timestamp,
    }
    receipt["receipt_fingerprint"] = fingerprint(receipt)
    receipt_errors = validate_schema(receipt, "database_storage_receipt.schema.json", STORAGE_RECEIPT_FILE)
    if receipt_errors:
        raise ValueError("generated storage receipt is invalid: " + "; ".join(receipt_errors))
    elements_receipt = Path(package["elements_snapshot_path"]) / "receipts" / STORAGE_RECEIPT_FILE
    release_receipt = Path(package["release_assets_path"]) / STORAGE_RECEIPT_FILE
    cards = read_jsonl(SOURCE_ARCHIVE_FILE) if SOURCE_ARCHIVE_FILE.exists() else []
    card = {
        "schema_version": "2.0.0",
        "id": f"grdr:source-archive:{package['source_slug']}",
        "source_id": project["source_id"],
        "repository": publication["repository_url"],
        "latest_snapshot": package["snapshot_id"],
        "release": publication["release_url"],
        "manifest": f"{publication['repository_url']}/releases/download/{package['release_tag']}/manifest.json",
        "archive_fingerprint": package["logical_content_fingerprint"],
        "core_version": package["core_version"],
        "status": "complete",
        "updated_at": timestamp,
        "runtime": {
            "protocol_version": package["runtime"]["protocol_version"],
            "asset": next(item["name"] for item in package["release_assets"] if item["component"] == "agent"),
            "entrypoint": f"agent/{package['runtime']['entrypoint']}",
            "agent_index": f"agent/{package['runtime']['agent_index']}",
            "operations": package["runtime"]["operations"],
        },
    }
    card_errors = validate_schema(card, "source_archive.schema.json", "source_archive")
    if card_errors:
        raise ValueError("generated central index card is invalid: " + "; ".join(card_errors))
    by_id = {item["id"]: item for item in cards}
    by_id[card["id"]] = card
    updated_cards = [by_id[key] for key in sorted(by_id)]
    updated_project = json.loads(json.dumps(project))
    updated_project["phase_states"]["completion_audit"] = {
        "state": "verified_complete",
        "completion_basis": "Step 3 stored one complete callable semantic snapshot in a verified GitHub Release and matching expanded Elements directory, verified full runtime variable resolution, then wrote the central source index card.",
        "evidence": project["phase_states"]["boundary"]["evidence"],
        "blockers": [],
        "updated_at": timestamp,
    }
    updated_project["workflow_status"] = "complete"
    updated_project["current_phase"] = "complete"
    updated_project["next_actions"] = ["database-storage-status"]
    append_history(updated_project, "record-database-storage-publication", "Verified GitHub publication, sealed the Storage receipt, and updated the GRDR central source snapshot card.")
    paths = [
        target / STORAGE_PUBLICATION_FILE,
        target / STORAGE_RECEIPT_FILE,
        elements_receipt,
        release_receipt,
        SOURCE_ARCHIVE_FILE,
        target / PROJECT_FILE,
    ]
    originals = {path: path.read_text(encoding="utf-8") if path.is_file() else None for path in paths}
    try:
        write_json(target / STORAGE_PUBLICATION_FILE, publication)
        write_json(target / STORAGE_RECEIPT_FILE, receipt)
        write_json(elements_receipt, receipt)
        write_json(release_receipt, receipt)
        write_jsonl(SOURCE_ARCHIVE_FILE, updated_cards)
        write_json(target / PROJECT_FILE, updated_project)
        audit = audit_database_storage(target)
        if audit["errors"] or not audit["storage_complete"]:
            raise ValueError("final Storage audit failed: " + "; ".join(audit["errors"]))
    except Exception:
        for path, content in originals.items():
            if content is None:
                path.unlink(missing_ok=True)
            else:
                atomic_write_text(path, content)
        raise
    return {"operation": "record_database_storage_publication", "receipt": receipt, "source_archive": card, "audit": audit}


def run_checked(command: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    completed = subprocess.run(command, cwd=cwd, capture_output=True, text=True)
    if completed.returncode:
        raise ValueError((completed.stderr or completed.stdout).strip() or "command failed: " + " ".join(command))
    return completed


def publish_database_storage(project_dir: str | Path) -> dict[str, Any]:
    target = resolve_project_dir(project_dir)
    audit = audit_database_storage(target)
    if audit["errors"] or not audit["ready_for_publish"]:
        raise ValueError("database storage is not ready for publication: " + "; ".join(audit["errors"] or audit["warnings"]))
    package = read_json(target / STORAGE_PACKAGE_FILE)
    repository = Path(package["source_repository_path"])
    run_checked(["gh", "auth", "status"], ROOT)
    if not (repository / ".git").is_dir():
        run_checked(["git", "init", "-b", "main"], repository)
    run_checked(["git", "add", "."], repository)
    status = run_checked(["git", "status", "--porcelain"], repository).stdout.strip()
    if status:
        run_checked(["git", "commit", "-m", f"store {package['source_id']} snapshot {package['snapshot_id']}"], repository)
    remote = subprocess.run(["git", "remote", "get-url", "origin"], cwd=repository, capture_output=True, text=True)
    if remote.returncode:
        run_checked(["gh", "repo", "create", package["source_repository"], "--private", "--source", str(repository), "--remote", "origin", "--push"], repository)
    else:
        run_checked(["git", "push", "-u", "origin", "HEAD"], repository)
    repository_view = run_checked(
        ["gh", "repo", "view", package["source_repository"], "--json", "nameWithOwner,url,visibility"],
        repository,
    )
    repository_state = json.loads(repository_view.stdout)
    if repository_state.get("nameWithOwner", "").casefold() != package["source_repository"].casefold():
        raise ValueError("GitHub repository identity differs from the Storage package")
    if repository_state.get("visibility") != "PRIVATE":
        raise ValueError("database source repositories must remain private")
    assets_path = Path(package["release_assets_path"])
    asset_paths = [str(assets_path / item["name"]) for item in package["release_assets"]] + [str(assets_path / "manifest.json")]
    existing = subprocess.run(["gh", "release", "view", package["release_tag"], "--repo", package["source_repository"]], cwd=repository, capture_output=True, text=True)
    if existing.returncode:
        run_checked(["gh", "release", "create", package["release_tag"], *asset_paths, "--repo", package["source_repository"], "--title", package["release_title"], "--notes", f"GRDR snapshot {package['snapshot_id']}"], repository)
    else:
        run_checked(["gh", "release", "upload", package["release_tag"], *asset_paths, "--clobber", "--repo", package["source_repository"]], repository)
    release_api = run_checked(
        ["gh", "api", f"repos/{package['source_repository']}/releases/tags/{package['release_tag']}"],
        repository,
    )
    release_state = json.loads(release_api.stdout)
    release_url = release_state["html_url"]
    expected_assets = {item["name"]: item for item in publication_asset_records(package)}
    remote_assets = {item["name"]: item for item in release_state.get("assets", [])}
    for name, expected in expected_assets.items():
        remote = remote_assets.get(name)
        if remote is None:
            raise ValueError(f"GitHub Release is missing uploaded asset {name}")
        if remote.get("size") != expected["size_bytes"]:
            raise ValueError(f"GitHub Release asset size differs for {name}")
        digest = remote.get("digest")
        if digest != f"sha256:{expected['sha256']}":
            raise ValueError(f"GitHub Release did not verify the expected SHA-256 digest for {name}")
    commit = run_checked(["git", "rev-parse", "HEAD"], repository).stdout.strip()
    publication = {
        "schema_version": "1.0.0",
        "project_id": package["project_id"],
        "source_id": package["source_id"],
        "snapshot_id": package["snapshot_id"],
        "repository_url": repository_state["url"],
        "release_url": release_url,
        "release_tag": package["release_tag"],
        "source_repository_commit": commit,
        "assets": publication_asset_records(package),
        "verified_at": now(),
    }
    publication["publication_fingerprint"] = fingerprint(publication)
    with tempfile.TemporaryDirectory() as temporary:
        publication_path = Path(temporary) / STORAGE_PUBLICATION_FILE
        write_json(publication_path, publication)
        result = record_database_storage_publication(target, publication_path)
    run_checked(["gh", "release", "upload", package["release_tag"], str(target / STORAGE_RECEIPT_FILE), "--clobber", "--repo", package["source_repository"]], repository)
    receipt_state = json.loads(run_checked(
        ["gh", "api", f"repos/{package['source_repository']}/releases/tags/{package['release_tag']}"],
        repository,
    ).stdout)
    remote_receipt = next((item for item in receipt_state.get("assets", []) if item.get("name") == STORAGE_RECEIPT_FILE), None)
    if remote_receipt is None or remote_receipt.get("size") != (target / STORAGE_RECEIPT_FILE).stat().st_size:
        raise ValueError("GitHub Release Storage receipt upload could not be verified")
    if remote_receipt.get("digest") != f"sha256:{sha256_file(target / STORAGE_RECEIPT_FILE)}":
        raise ValueError("GitHub Release Storage receipt SHA-256 could not be verified")
    return {"operation": "publish_database_storage", "repository_url": publication["repository_url"], "release_url": release_url, **result}


def database_storage_status(project_dir: str | Path) -> dict[str, Any]:
    return {**audit_database_storage(project_dir), "operation": "database_storage_status"}
