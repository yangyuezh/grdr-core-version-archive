def archive_members(path: Path) -> dict[str, dict[str, Any]]:
    result = {}
    with tarfile.open(path, mode="r:gz") as archive:
        for member in archive.getmembers():
            if not member.isfile():
                continue
            handle = archive.extractfile(member)
            if handle is None:
                continue
            digest = hashlib.sha256()
            size = 0
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
                size += len(chunk)
            result[member.name] = {"sha256": digest.hexdigest(), "size_bytes": size}
    return result


