def write_generated(path: Path, content: str) -> None:
    if path.exists():
        current = path.read_text(encoding="utf-8")
        if current == content:
            return
        if not current.startswith((GENERATED_MARKER, GENERATED_PY_MARKER)):
            raise ValueError(f"refusing to overwrite a non-GRDR file: {path}")
    atomic_write_text(path, content)


def write_source_readme(path: Path, generated: str) -> None:
    if path.is_file():
        current = path.read_text(encoding="utf-8")
        if HUMAN_READABLE_MARKER in current:
            human = HUMAN_READABLE_MARKER + current.split(HUMAN_READABLE_MARKER, 1)[1]
            generated = generated.rstrip() + "\n\n" + human.lstrip()
    write_generated(path, generated)


