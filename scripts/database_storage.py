def is_ignored_filesystem_metadata(path: Path) -> bool:
    """Exclude host filesystem sidecars from the logical database snapshot."""
    return any(part in IGNORED_FILESYSTEM_METADATA or part.startswith("._") for part in path.parts)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def file_record(
    path: Path,
    relative: str,
    component: str,
    locations: list[str] | None = None,
) -> dict[str, Any]:
    record = {
        "path": relative,
        "component": component,
        "sha256": sha256_file(path),
        "size_bytes": path.stat().st_size,
    }
    if locations is not None:
        record["locations"] = sorted(locations)
    return record


def asset_record(path: Path, component: str, logical_paths: list[str]) -> dict[str, Any]:
    return {
        "name": path.name,
        "component": component,
        "sha256": sha256_file(path),
        "size_bytes": path.stat().st_size,
        "logical_paths": sorted(logical_paths),
    }


def resolve_input(value: str, base: Path) -> Path:
    path = Path(value).expanduser()
    if not path.is_absolute():
        path = base / path
    return path.resolve()


def checked_files(path: Path) -> list[Path]:
    if not path.exists():
        raise ValueError(f"storage input does not exist: {path}")
    if path.is_symlink():
        raise ValueError(f"storage inputs cannot be symbolic links: {path}")
    if path.is_file():
        return [path]
    files = []
    for item in sorted(path.rglob("*")):
        if is_ignored_filesystem_metadata(item.relative_to(path)):
            continue
        if item.is_symlink():
            raise ValueError(f"storage inputs cannot contain symbolic links: {item}")
        if item.is_file():
            files.append(item)
    if not files:
        raise ValueError(f"storage input contains no files: {path}")
    return files


def copy_input(source: Path, destination: Path) -> list[Path]:
    files = checked_files(source)
    for item in files:
        relative = Path(item.name) if source.is_file() else item.relative_to(source)
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(item, target)
    return [destination / (Path(item.name) if source.is_file() else item.relative_to(source)) for item in files]


def path_is_within(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
        return True
    except ValueError:
        return False


def copy_project_knowledge(
    project_dir: Path,
    destination: Path,
    observation_roots: list[Path] | None = None,
) -> None:
    observation_roots = [item.resolve() for item in (observation_roots or [])]
    excluded = {STORAGE_PACKAGE_FILE, STORAGE_PUBLICATION_FILE, STORAGE_RECEIPT_FILE}
    for source in sorted(project_dir.rglob("*")):
        if is_ignored_filesystem_metadata(source.relative_to(project_dir)):
            continue
        if source.is_symlink():
            raise ValueError(f"deep-map project contains an unsupported symbolic link: {source}")
        if not source.is_file() or source.name in excluded or "__pycache__" in source.parts:
            continue
        resolved = source.resolve()
        if any(resolved == root or path_is_within(resolved, root) for root in observation_roots):
            continue
        relative = source.relative_to(project_dir)
        target = destination / "project" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)


def display_text(record: dict[str, Any]) -> str:
    values = []
    for key in ("name", "label", "title", "description", "definition"):
        value = record.get(key)
        if isinstance(value, str):
            values.append(value)
    aliases = record.get("aliases")
    if isinstance(aliases, list):
        values.extend(str(value) for value in aliases)
    return " | ".join(dict.fromkeys(values))


def build_agent_index(project_dir: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(destination)
    try:
        connection.executescript(
            """
            PRAGMA journal_mode=OFF;
            PRAGMA synchronous=OFF;
            CREATE TABLE metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
            CREATE TABLE records (
              id TEXT PRIMARY KEY,
              entity_type TEXT NOT NULL,
              label TEXT NOT NULL,
              search_text TEXT NOT NULL,
              payload_json TEXT NOT NULL
            );
            CREATE INDEX records_entity_type ON records(entity_type);
            CREATE INDEX records_label ON records(label);
            CREATE TABLE relationships (
              id TEXT PRIMARY KEY,
              subject_id TEXT,
              predicate TEXT,
              object_id TEXT,
              payload_json TEXT NOT NULL
            );
            CREATE INDEX relationships_subject ON relationships(subject_id);
            CREATE INDEX relationships_object ON relationships(object_id);
            """
        )
        project = read_json(project_dir / PROJECT_FILE)
        connection.executemany(
            "INSERT INTO metadata(key, value) VALUES (?, ?)",
            [("project_id", project["id"]), ("source_id", project["source_id"]), ("built_at", now())],
        )
        staging = project_dir / STAGING_DIR
        for path in sorted(staging.glob("*.jsonl")):
            if is_ignored_filesystem_metadata(path.relative_to(staging)):
                continue
            entity_type = path.stem
            for record in read_jsonl(path):
                payload = json.dumps(record, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
                if entity_type == "relationships":
                    connection.execute(
                        "INSERT INTO relationships VALUES (?, ?, ?, ?, ?)",
                        (record["id"], record.get("subject_id"), record.get("predicate"), record.get("object_id"), payload),
                    )
                else:
                    label = str(record.get("label") or record.get("name") or record.get("title") or record["id"])
                    connection.execute(
                        "INSERT INTO records VALUES (?, ?, ?, ?, ?)",
                        (record["id"], entity_type, label, display_text(record), payload),
                    )
        try:
            connection.execute("CREATE VIRTUAL TABLE record_search USING fts5(id UNINDEXED, label, search_text)")
            connection.execute("INSERT INTO record_search SELECT id, label, search_text FROM records")
        except sqlite3.OperationalError:
            connection.execute("CREATE INDEX records_search_text ON records(search_text)")
        connection.commit()
        connection.execute("VACUUM")
    finally:
        connection.close()


def stage_source_runtime(spec: dict[str, Any], project: dict[str, Any], agent_dir: Path) -> dict[str, Any]:
    descriptor_path = resolve_input(spec["runtime"]["descriptor"], ROOT)
    descriptor = read_json(descriptor_path)
    errors = validate_schema(descriptor, "source_runtime.schema.json", RUNTIME_DESCRIPTOR_FILE)
    if errors:
        raise ValueError("invalid source runtime descriptor: " + "; ".join(errors))
    if descriptor["source_id"] != project["source_id"]:
        raise ValueError("source runtime descriptor source_id does not match the deep-map project")
    inputs = [resolve_input(value, ROOT) for value in spec["runtime"]["files"]]
    names = [path.name for path in inputs]
    if len(names) != len(set(names)):
        raise ValueError("source runtime files must have unique basenames")
    if descriptor["entrypoint"] not in names:
        raise ValueError("source runtime entrypoint is absent from runtime.files")
    agent_dir.mkdir(parents=True, exist_ok=True)
    write_json(agent_dir / RUNTIME_DESCRIPTOR_FILE, descriptor)
    for source in inputs:
        if not source.is_file() or source.is_symlink():
            raise ValueError(f"runtime input must be a regular file: {source}")
        shutil.copy2(source, agent_dir / source.name)
    return descriptor


def run_source_runtime_self_test(agent_dir: Path, descriptor: dict[str, Any]) -> dict[str, Any]:
    entrypoint = agent_dir / descriptor["entrypoint"]
    index = agent_dir / descriptor["agent_index"]
    try:
        completed = subprocess.run(
            [sys.executable, str(entrypoint), "self-test", "--index", str(index)],
            cwd=agent_dir,
            capture_output=True,
            text=True,
            timeout=120,
        )
    except subprocess.TimeoutExpired as exc:
        raise ValueError("source runtime self-test exceeded 120 seconds") from exc
    if completed.returncode:
        detail = (completed.stderr or completed.stdout).strip()
        raise ValueError(f"source runtime self-test failed: {detail}")
    try:
        report = json.loads(completed.stdout)
    except json.JSONDecodeError as exc:
        raise ValueError("source runtime self-test did not emit one JSON object") from exc
    if not isinstance(report, dict):
        raise ValueError("source runtime self-test result must be a JSON object")
    required = {
        "source_id": descriptor["source_id"],
        "status": "ready",
        "unresolved_variable_count": 0,
    }
    for key, expected in required.items():
        if report.get(key) != expected:
            raise ValueError(f"source runtime self-test {key} must equal {expected!r}")
    connection = sqlite3.connect(index)
    try:
        indexed_variable_count = connection.execute(
            "SELECT COUNT(*) FROM records WHERE entity_type = 'variables'"
        ).fetchone()[0]
    finally:
        connection.close()
    variable_count = report.get("variable_count")
    resolvable_count = report.get("resolvable_variable_count")
    if variable_count != indexed_variable_count:
        raise ValueError("source runtime self-test variable count differs from the Agent index")
    if resolvable_count != variable_count:
        raise ValueError("source runtime self-test did not resolve every registered variable")
    return report


def indexed_variable_ids(index: Path) -> list[str]:
    connection = sqlite3.connect(index)
    try:
        return [
            row[0]
            for row in connection.execute(
                "SELECT id FROM records WHERE entity_type = 'variables' ORDER BY id"
            )
        ]
    finally:
        connection.close()


def route_policies(spec: dict[str, Any]) -> dict[str, list[str]]:
    replication = spec["observation_policy"]["replication"]
    routes = spec["observation_policy"]["online_access"]["routes"]
    classes: set[str] = set()
    has_official = any(item["authority"] == "official" for item in routes)
    has_reproducible_official = any(
        item["authority"] == "official"
        and item["freshness"] in {"version_pinned", "frozen_snapshot"}
        for item in routes
    )
    if has_official:
        classes.add("official_online")
    if any(item["access_method"] == "grdr_release_snapshot" for item in routes):
        classes.add("github_release_snapshot")
    if (
        spec.get("schema_version") == "4.1.0"
        and "github_release" in replication["placements"]
    ):
        classes.add("local_snapshot_cache")
    if "elements" in replication["placements"]:
        classes.add("elements_mirror")
    if "object_store" in replication["placements"]:
        classes.add("mounted_object_store")
    return {
        "latest": [
            item for item in (
                "official_online",
                "github_release_snapshot",
                "local_snapshot_cache",
                "elements_mirror",
                "mounted_object_store",
            ) if item in classes
        ],
        "reproducible": [
            item for item in (
                "github_release_snapshot",
                "local_snapshot_cache",
                "elements_mirror",
                "mounted_object_store",
                "official_online",
            ) if item in classes and (item != "official_online" or has_reproducible_official)
        ],
        "offline": [
            item for item in (
                "local_snapshot_cache",
                "elements_mirror",
                "mounted_object_store",
            ) if item in classes
        ],
    }


def build_online_access_manifest(
    spec: dict[str, Any],
    descriptor: dict[str, Any],
    variable_count: int,
) -> dict[str, Any]:
    access = spec["observation_policy"]["online_access"]
    replication = spec["observation_policy"]["replication"]
    routes = access["routes"]
    route_ids = [item["route_id"] for item in routes]
    if len(route_ids) != len(set(route_ids)):
        raise ValueError("online access routes must have unique route_id values")
    supported_methods = set(descriptor["supported_access_methods"])
    unknown_methods = sorted({item["access_method"] for item in routes} - supported_methods)
    if unknown_methods:
        raise ValueError(
            "source runtime does not declare every online access method: "
            + ", ".join(unknown_methods)
        )
    official_routes = [item for item in routes if item["authority"] == "official"]
    official_status = access["official_access"]["status"]
    if official_status == "callable" and not official_routes:
        raise ValueError("callable official access requires at least one official online route")
    if official_status == "unavailable" and official_routes:
        raise ValueError("unavailable official access cannot declare an official online route")
    for route in routes:
        if route["authority"] == "official":
            if not route["access_method"].startswith("official_"):
                raise ValueError(f"official route {route['route_id']} uses a non-official access method")
            if route["verification"] != "live_runtime_test":
                raise ValueError(f"official route {route['route_id']} must use live_runtime_test")
        else:
            if route["access_method"] != "grdr_release_snapshot":
                raise ValueError(f"GRDR route {route['route_id']} must be a Release snapshot")
            if route["verification"] != "staged_release_snapshot_test":
                raise ValueError(f"GRDR route {route['route_id']} must use staged_release_snapshot_test")
            if route["freshness"] != "frozen_snapshot":
                raise ValueError(f"GRDR Release route {route['route_id']} must be a frozen snapshot")
            if "github_release" not in replication["placements"]:
                raise ValueError("GRDR Release online access requires github_release observation placement")
    if replication["mode"] == "no_mirror" and any(
        item["authority"] == "grdr" for item in routes
    ):
        raise ValueError("no_mirror cannot claim a GRDR Release observation route")
    policies = route_policies(spec)
    if not policies["latest"] or not policies["reproducible"]:
        raise ValueError("online access must provide both latest and reproducible route policies")
    manifest = {
        "schema_version": "1.0.0",
        "source_id": spec["source_id"],
        "snapshot_id": spec["snapshot_id"],
        "status": "callable_complete",
        "completion_requirement": access["completion_requirement"],
        "official_access": access["official_access"],
        "routes": routes,
        "coverage": {
            "claim": "all_registered_variables",
            "expected_variable_count": variable_count,
        },
        "route_policies": policies,
    }
    errors = validate_schema(manifest, "online_access_manifest.schema.json", ONLINE_ACCESS_FILE)
    if errors:
        raise ValueError("generated online access manifest is invalid: " + "; ".join(errors))
    return manifest


def run_source_runtime_online_test(
    agent_dir: Path,
    descriptor: dict[str, Any],
    snapshot_root: Path,
) -> dict[str, Any]:
    entrypoint = agent_dir / descriptor["entrypoint"]
    index = agent_dir / descriptor["agent_index"]
    access_path = agent_dir / descriptor["online_access_manifest"]
    access = read_json(access_path)
    environment = {
        **os.environ,
        "GRDR_SOURCE_SNAPSHOT_ROOT": str(snapshot_root),
        "GRDR_OBSERVATION_REPLICATION_MODE": read_json(access_path).get("replication_mode", "independent"),
        "GRDR_OBSERVATION_ROOT": str(snapshot_root / "observations") if (snapshot_root / "observations").is_dir() else "",
        "GRDR_ONLINE_ACCESS_MANIFEST": str(access_path),
        "GRDR_ONLINE_ACCESS_ROUTES": json.dumps(access["routes"], separators=(",", ":")),
    }
    try:
        completed = subprocess.run(
            [
                sys.executable,
                str(entrypoint),
                "self-test-online",
                "--index",
                str(index),
                "--access-manifest",
                str(access_path),
            ],
            cwd=agent_dir,
            env=environment,
            capture_output=True,
            text=True,
            timeout=300,
        )
    except subprocess.TimeoutExpired as exc:
        raise ValueError("source runtime online self-test exceeded 300 seconds") from exc
    if completed.returncode:
        detail = (completed.stderr or completed.stdout).strip()
        raise ValueError(f"source runtime online self-test failed: {detail}")
    try:
        report = json.loads(completed.stdout)
    except json.JSONDecodeError as exc:
        raise ValueError("source runtime online self-test did not emit one JSON object") from exc
    errors = validate_schema(report, "online_runtime_audit.schema.json", ONLINE_RUNTIME_AUDIT_FILE)
    if errors:
        raise ValueError("invalid source runtime online self-test: " + "; ".join(errors))
    variable_ids = indexed_variable_ids(index)
    if report["source_id"] != descriptor["source_id"] or report["snapshot_id"] != access["snapshot_id"]:
        raise ValueError("source runtime online self-test identity differs from the snapshot")
    if report["variable_count"] != len(variable_ids):
        raise ValueError("source runtime online variable count differs from the Agent index")
    if report["online_callable_variable_count"] != len(variable_ids):
        raise ValueError("source runtime online self-test did not cover every registered variable")
    coverage_ids = [item["variable_id"] for item in report["variable_routes"]]
    if len(coverage_ids) != len(set(coverage_ids)) or sorted(coverage_ids) != variable_ids:
        raise ValueError("online variable-route coverage does not enumerate the exact Agent-index variables")
    declared_routes = {item["route_id"]: item for item in access["routes"]}
    reported_routes = {item["route_id"]: item for item in report["route_results"]}
    if len(reported_routes) != len(report["route_results"]) or set(reported_routes) != set(declared_routes):
        raise ValueError("online route audit does not exactly cover the declared routes")
    for route_id, declared in declared_routes.items():
        result = reported_routes[route_id]
        if result["access_method"] != declared["access_method"] or result["authority"] != declared["authority"]:
            raise ValueError(f"online route audit differs from declaration for {route_id}")
    for item in report["variable_routes"]:
        if not set(item["route_ids"]).issubset(declared_routes):
            raise ValueError(f"online variable coverage names an undeclared route for {item['variable_id']}")
    return report


def create_deterministic_tar_gz(source: Path, output: Path, archive_root: str) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as compressed:
            with tarfile.open(fileobj=compressed, mode="w", format=tarfile.PAX_FORMAT) as archive:
                for path in sorted(source.rglob("*")):
                    if is_ignored_filesystem_metadata(path.relative_to(source)):
                        continue
                    if not path.is_file():
                        continue
                    relative = path.relative_to(source)
                    info = archive.gettarinfo(str(path), arcname=str(Path(archive_root) / relative))
                    info.uid = info.gid = 0
                    info.uname = info.gname = ""
                    info.mtime = 0
                    info.mode = 0o644
                    with path.open("rb") as handle:
                        archive.addfile(info, handle)


def inventory(
    logical_root: Path,
    component_locations: dict[str, list[str]] | None = None,
) -> list[dict[str, Any]]:
    records = []
    for path in sorted(logical_root.rglob("*")):
        if is_ignored_filesystem_metadata(path.relative_to(logical_root)):
            continue
        if not path.is_file():
            continue
        relative = path.relative_to(logical_root).as_posix()
        if relative.startswith("receipts/"):
            continue
        component = relative.split("/", 1)[0]
        locations = component_locations.get(component) if component_locations is not None else None
        records.append(file_record(path, relative, component, locations))
    return records


def record_without_locations(record: dict[str, Any]) -> dict[str, Any]:
    return {key: value for key, value in record.items() if key != "locations"}


def records_for_location(logical_files: list[dict[str, Any]], location: str) -> list[dict[str, Any]]:
    return [
        record_without_locations(item)
        for item in logical_files
        if location in item.get("locations", [])
    ]


def content_records(logical_files: list[dict[str, Any]], component: str) -> list[dict[str, Any]]:
    return [
        record_without_locations(item)
        for item in logical_files
        if item["component"] == component
    ]


def component_location_map(spec: dict[str, Any]) -> dict[str, list[str]]:
    placements = spec["observation_policy"]["replication"]["placements"]
    observation_locations = [
        item for item in ("github_release", "elements", "object_store")
        if item in placements
    ]
    if spec.get("schema_version") == "4.1.0":
        return {
            "knowledge": ["github_release"],
            "agent": ["github_release"],
            "observations": [
                item for item in observation_locations if item != "elements"
            ],
        }
    return {
        "knowledge": ["elements", "github_release"],
        "agent": ["elements", "github_release"],
        "observations": observation_locations,
    }


