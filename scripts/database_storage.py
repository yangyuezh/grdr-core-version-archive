def classify_observation_size(total_bytes: int | None, policy: dict[str, Any]) -> str:
    if total_bytes is None:
        return "unknown"
    if isinstance(policy.get("elements_full_mirror_max_bytes"), int):
        lower_limit = min(
            policy["github_release_observation_max_bytes"],
            policy["elements_full_mirror_max_bytes"],
        )
        upper_limit = max(
            policy["github_release_observation_max_bytes"],
            policy["elements_full_mirror_max_bytes"],
        )
        if total_bytes <= lower_limit:
            return "small"
        if total_bytes <= upper_limit:
            return "medium"
        return "large"
    if total_bytes <= policy["github_release_observation_max_bytes"]:
        return "small"
    return "large"


def assess_storage_capacity(
    spec: dict[str, Any],
    observation_files: list[dict[str, Any]],
) -> dict[str, Any]:
    policy = storage_capacity_policy()
    captured_bytes = sum(item["size_bytes"] for item in observation_files)
    replication = spec["observation_policy"]["replication"]
    mode = replication["mode"]
    estimate = replication.get("capacity_estimate")
    if estimate is not None:
        estimated_total = estimate["estimated_total_bytes"]
        estimate_basis = estimate["basis"]
    elif mode == "full_mirror":
        estimated_total = captured_bytes
        estimate_basis = "Full mirror: captured bytes equal the declared observation denominator."
    else:
        estimated_total = None
        estimate_basis = "No total upstream byte estimate was supplied; size class is unknown."
    size_class = classify_observation_size(estimated_total, policy)
    placements = set(replication["placements"])
    errors = []
    if "github_release" in placements and captured_bytes > policy["github_release_observation_max_bytes"]:
        errors.append(
            "captured observations exceed the configured GitHub Release observation limit; "
            "remove github_release from placements or raise the external deployment policy"
        )
    if errors:
        raise ValueError("; ".join(errors))
    if size_class == "small":
        recommendation = "captured observations are eligible for GitHub Release replication"
    elif size_class == "large":
        recommendation = "prefer partitioned_mirror or no_mirror; online access remains mandatory"
    else:
        recommendation = "supply capacity_estimate before using a size-class recommendation"
    return {
        "policy_source": policy["source"],
        "estimated_total_bytes": estimated_total,
        "estimate_basis": estimate_basis,
        "captured_bytes": captured_bytes,
        "size_class": size_class,
        "github_release_observation_max_bytes": policy["github_release_observation_max_bytes"],
        "github_release_asset_max_bytes": policy["github_release_asset_max_bytes"],
        "selected_mode": mode,
        "selected_placements": sorted(placements),
        "recommendation": recommendation,
        "policy_compliant": True,
    }


def partition_file_records(observation_files: list[dict[str, Any]], name: str) -> list[dict[str, Any]]:
    prefix = f"observations/{name}/"
    return sorted(
        [
            {
                "relative_path": item["path"].removeprefix(prefix),
                "sha256": item["sha256"],
                "size_bytes": item["size_bytes"],
            }
            for item in observation_files
            if item["path"].startswith(prefix)
        ],
        key=lambda item: item["relative_path"],
    )


def validate_partition_manifest_document(
    manifest: dict[str, Any],
    spec: dict[str, Any],
    observation_files: list[dict[str, Any]],
) -> None:
    errors = validate_schema(manifest, "observation_partition_manifest.schema.json", "partition_manifest")
    if errors:
        raise ValueError("invalid partition manifest: " + "; ".join(errors))
    if manifest["source_id"] != spec["source_id"] or manifest["snapshot_id"] != spec["snapshot_id"]:
        raise ValueError("partition manifest Source or snapshot identity differs from the Storage specification")
    partition_names = [item["name"] for item in manifest["partitions"]]
    expected_names = [item["name"] for item in spec["observation_inputs"]]
    if len(partition_names) != len(set(partition_names)):
        raise ValueError("partition manifest contains duplicate partition names")
    if sorted(partition_names) != sorted(expected_names):
        raise ValueError("partition manifest names differ from observation_inputs")
    if manifest["partition_count"] != len(manifest["partitions"]):
        raise ValueError("partition manifest partition_count is stale")
    manifest_file_count = sum(len(item["files"]) for item in manifest["partitions"])
    if manifest["file_count"] != manifest_file_count:
        raise ValueError("partition manifest file_count is stale")
    if manifest_file_count != len(observation_files):
        raise ValueError("partition manifest does not enumerate every captured observation file")
    for partition in manifest["partitions"]:
        expected_files = partition_file_records(observation_files, partition["name"])
        actual_files = sorted(partition["files"], key=lambda item: item["relative_path"])
        if actual_files != expected_files:
            raise ValueError(
                f"partition manifest files or hashes differ for partition {partition['name']}"
            )


def validate_observation_policy(
    spec: dict[str, Any],
    spec_path: Path,
    observation_files: list[dict[str, Any]],
) -> dict[str, Any] | None:
    policy = spec["observation_policy"]
    replication = policy["replication"]
    mode = replication["mode"]
    completeness = replication["completeness"]
    actual_files = len(observation_files)
    actual_partitions = len(spec["observation_inputs"])
    if mode in {"full_mirror", "partitioned_mirror"}:
        if actual_files == 0:
            raise ValueError(f"{mode} requires at least one actual observation-data file")
        if sum(item["size_bytes"] for item in observation_files) == 0:
            raise ValueError("observation-data inputs contain zero total bytes")
    if completeness["expected_file_count"] is not None and completeness["expected_file_count"] != actual_files:
        raise ValueError(
            f"observation completeness expected_file_count={completeness['expected_file_count']} "
            f"but captured {actual_files}"
        )
    if completeness["expected_partition_count"] is not None and completeness["expected_partition_count"] != actual_partitions:
        raise ValueError(
            f"observation completeness expected_partition_count={completeness['expected_partition_count']} "
            f"but captured {actual_partitions}"
        )
    partition_record = None
    if mode == "partitioned_mirror":
        path = resolve_input(replication["partition_manifest"], spec_path.parent)
        if not path.is_file() or path.is_symlink():
            raise ValueError(f"partition manifest must be a regular file: {path}")
        try:
            manifest = read_json(path)
        except (OSError, json.JSONDecodeError) as exc:
            raise ValueError(f"partition manifest is not valid JSON: {path}") from exc
        validate_partition_manifest_document(manifest, spec, observation_files)
        partition_record = {
            "source_path": str(path),
            "sha256": sha256_file(path),
            "size_bytes": path.stat().st_size,
            "partition_count": manifest["partition_count"],
            "file_count": manifest["file_count"],
        }
    external_types = [item["type"] for item in replication["external_locations"]]
    if len(external_types) != len(set(external_types)):
        raise ValueError("observation external locations must have unique types")
    placements = set(replication["placements"])
    for external in replication["external_locations"]:
        if external["type"] not in placements:
            raise ValueError(f"external location {external['type']} is absent from observation placements")
        if external["type"] == "object_store":
            if external["verification"] != "copied_and_hashed" or not external["local_path"]:
                raise ValueError("object_store requires copied_and_hashed verification and a mounted local_path")
    for location in ("object_store",):
        if location in placements and location not in external_types:
            raise ValueError(f"observation placement {location} requires one external_locations record")
    cache = policy["cache"]
    if cache["mode"] == "on_demand":
        if not cache["research_project_snapshots"] or cache["root"] != "research_project":
            raise ValueError("on-demand cache requires research-project snapshots")
    elif cache["research_project_snapshots"] or cache["root"] is not None:
        raise ValueError("disabled cache cannot declare research-project snapshot storage")
    return partition_record


def duplicate_cross_component_hashes(logical_files: list[dict[str, Any]]) -> set[str]:
    knowledge_hashes = {
        item["sha256"] for item in logical_files if item["component"] == "knowledge"
    }
    observation_hashes = {
        item["sha256"] for item in logical_files if item["component"] == "observations"
    }
    return knowledge_hashes & observation_hashes


